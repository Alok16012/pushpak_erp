// Regenerates src/lib/demo-data.ts from a running API that has been seeded with
// `npm run seed` in backend/. The demo dataset is entirely synthetic (DEMO-* codes
// and @demo.idealdigiskills.local addresses), so the snapshot is safe to commit.
//
//   API_URL=http://127.0.0.1:5050/api/v1 \
//   DEMO_IDENTIFIER=admin@example.com DEMO_PASSWORD=... \
//   node scripts/capture-demo-data.mjs

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const API_URL = process.env.API_URL || "http://127.0.0.1:5050/api/v1";
const identifier = process.env.DEMO_IDENTIFIER;
const password = process.env.DEMO_PASSWORD;
if (!identifier || !password) throw new Error("Set DEMO_IDENTIFIER and DEMO_PASSWORD");

const login = await fetch(`${API_URL}/auth/login`, {
  method: "POST",
  headers: { "Content-Type": "application/json" },
  body: JSON.stringify({ identifier, password }),
}).then(r => r.json());
if (!login.success) throw new Error(`Login failed: ${login.message}`);
const headers = { Authorization: `Bearer ${login.data.accessToken}` };

const get = async path => {
  const body = await fetch(`${API_URL}${path}`, { headers }).then(r => r.json());
  if (!body.success) throw new Error(`${path} failed: ${body.message}`);
  return body.data;
};

const collections = {};
for (const path of ["/core/dashboard", "/core/students", "/core/courses", "/core/batches", "/core/attendance", "/core/enquiries", "/core/exams", "/core/fees/invoices"]) {
  collections[path] = await get(path);
}

const documents = {};
for (const student of collections["/core/students"]) {
  documents[student.id] = await get(`/core/documents/students/${student.id}`);
}

const out = fileURLToPath(new URL("../src/lib/demo-data.ts", import.meta.url));
writeFileSync(out, `// Generated by scripts/capture-demo-data.mjs — do not edit by hand.
// Synthetic seed data only; contains no real student or staff records.
export const demoCollections: Record<string, unknown> = ${JSON.stringify(collections, null, 1)};

export const demoDocuments: Record<string, unknown> = ${JSON.stringify(documents, null, 1)};
`);
console.log(`Wrote ${out}`);
